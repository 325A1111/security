// Helper to shuffle an array using Fisher-Yates algorithm
export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Generate a fresh set of questions with randomized question order and randomized choices
// count: number of questions to select (default: 10, or up to 20)
export function getShuffledQuestions(count = 10): Question[] {
  // 1. Shuffle the order of the questions
  const shuffledQuestionsOrder = shuffleArray(QUIZ_QUESTIONS).slice(0, count);

  // 2. For each question, shuffle its 4 options and update correctIndex
  return shuffledQuestionsOrder.map((q) => {
    const correctText = q.options[q.correctIndex];
    const shuffledOptions = shuffleArray(q.options);
    const newCorrectIndex = shuffledOptions.indexOf(correctText);

    return {
      ...q,
      options: shuffledOptions,
      correctIndex: newCorrectIndex,
    };
  });
}

// Helper to calculate total damage for a given set of wrong answers
export function calculateDamage(wrongQuestions: Question[]): {
  totalDamage: number;
  incidentCount: number;
  bankruptcyReason: string;
  isBankrupt: boolean;
  stockDropPercent: number;
} {
  if (wrongQuestions.length === 0) {
    return {
      totalDamage: 0,
      incidentCount: 0,
      bankruptcyReason: "なし（完全防衛達成）",
      isBankrupt: false,
      stockDropPercent: 0
    };
  }

  // Calculate base damage
  const baseTotal = wrongQuestions.reduce((acc, q) => acc + q.baseDamage, 0);
  
  // The more mistakes, the exponentially worse the multiplier!
  // 1 mistake: x1.0
  // 2 mistakes: x1.4
  // 3 mistakes: x1.85
  // 4 mistakes: x2.4
  // 5 mistakes: x3.2
  // 10 mistakes: x6.5
  const multiplier = 1 + (wrongQuestions.length - 1) * 0.48;
  const scaledDamage = Math.round(baseTotal * multiplier);

  const stockDrop = Math.min(99.9, Math.round(30 + wrongQuestions.length * 6.5 + wrongQuestions.length * wrongQuestions.length * 0.4));

  return {
    totalDamage: scaledDamage,
    incidentCount: wrongQuestions.length,
    bankruptcyReason: wrongQuestions.map((q) => q.incidentName).join("、"),
    isBankrupt: true,
    stockDropPercent: stockDrop
  };
}
